# DUC_UPDATE_INSTRUCTIONS
# ---------------------------------------------------------------------------
# End-to-end instructions governing the UPDATE mode workflow.  These
# instructions are combined with section-specific context at runtime by
# ReverseDocumentHelper to form the complete system prompt for the Architect
# Agent during an incremental document update.
# ---------------------------------------------------------------------------

DUC_UPDATE_INSTRUCTIONS: str = """\
## UPDATE Mode — Document Update Workflow Instructions

Follow these steps **in order** to perform an incremental update of an \
existing Technical Specification.  The goal is to regenerate **only** the \
sections whose underlying code has meaningfully changed, while preserving \
everything else verbatim.

### Step 1 — Receive Inputs

You will receive the following inputs at the start of the UPDATE workflow:

- **Previous Technical Specification:** The full Markdown text of the last \
generated Technical Specification document.  Internalize its structure, \
section headings, and content.
- **Repository Reference:** Access to the current repository (via the \
Context Searcher Agent and its 8 search tools) so you can explore the \
codebase as it exists now.
- **Head Commit Hash:** The commit hash at which the previous spec was \
generated, enabling delta analysis.

### Step 2 — Explore Current Repository State

Delegate to the **Context Searcher Agent** to systematically explore the \
current repository.

- Request a full structural overview (root files, directories, manifests).
- Request targeted exploration of areas corresponding to each Technical \
Specification section.
- Gather context on new files, modified files, deleted files, dependency \
changes, and configuration changes.

### Step 3 — Compare Context Against Previous Specification

For **each section** of the previous Technical Specification:

1. Apply the **Change Identification Rules** to understand what has changed \
in the repository since the previous specification.
2. Apply the **Section Comparison Rules** (Comparisons 1–5) to determine \
whether the section is affected by those changes.
3. Record your classification (``CHANGED`` or ``UNCHANGED``) along with a \
brief justification.

### Step 4 — Produce Structured Classification Output

Output your classifications using the ``DocumentSections`` Pydantic model:

```
DocumentSections(
    sections=[
        DocumentSection(title="1. INTRODUCTION", content="...", status="UNCHANGED"),
        DocumentSection(title="2. SYSTEM OVERVIEW", content="...", status="CHANGED"),
        ...
    ]
)
```

- Every section from the previous Technical Specification **must** appear in \
your output.  Do not silently drop any sections.
- Use the ``DocumentSectionStatus`` enum values exactly: ``"CHANGED"`` or \
``"UNCHANGED"``.

### Step 5 — Handle UNCHANGED Sections

For each section classified as ``UNCHANGED``:

- The orchestrator will invoke ``copy_old_tech_spec_section()`` to copy the \
section's content **verbatim** from the previous Technical Specification.
- Fuzzy heading matching (via the ``thefuzz`` library) is used to locate the \
correct section in the previous document, so your ``title`` field must be \
close to the original heading.
- **You do not need to regenerate any content** for these sections.

### Step 6 — Handle CHANGED Sections

For each section classified as ``CHANGED``:

- The orchestrator will invoke the **Author Agent** to regenerate the \
section using the updated repository context.
- The Author Agent receives the section title, section-specific prompt \
template, and all gathered context.
- The regenerated content replaces the old section entirely.

### Step 7 — Preserve Document Structure

Throughout the update process:

- **Maintain section ordering** — Sections must appear in the same order as \
the original document.
- **Maintain section numbering** — Section numbers (1, 2, 3, …) and \
sub-section numbers (1.1, 1.2, …) must remain consistent.
- **Do not add or remove sections** unless the repository changes explicitly \
warrant it (e.g., a completely new architectural component that demands its \
own section).

### Step 8 — Validate Cross-References

After all sections are processed (either copied or regenerated):

- Verify that **cross-references** between sections remain valid.  For \
example, if Section 3 references "See Section 5.2", confirm that Section 5.2 \
still exists and covers the referenced topic.
- If a cross-reference target has been substantially changed, ensure the \
referencing section is also classified as ``CHANGED`` so it can be updated \
accordingly.
- Flag any broken cross-references for resolution during regeneration.

### Summary of Key Principles

| Principle | Description |
|-----------|-------------|
| **Minimal disruption** | Default to ``UNCHANGED``; only flag sections with clear evidence of impact |
| **Complete coverage** | Every section of the previous spec must appear in the output |
| **Evidence-based** | Every ``CHANGED`` classification must cite specific code-level changes |
| **Structured output** | Use ``DocumentSections`` Pydantic model for machine-parseable results |
| **Ordering preservation** | Maintain the original section order and numbering scheme |
| **Cross-reference integrity** | Validate inter-section references after classification |
"""
